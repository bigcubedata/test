def enc(rows):
    """rows: 8 行、每行 8 个 '.'/'1'/'2'/'3' 字符 → 16 字节平面数据。"""
    assert len(rows) == 8, rows
    lo = []
    hi = []
    for r in rows:
        r = (r + "........")[:8]
        b0 = b1 = 0
        for i, ch in enumerate(r):
            c = 0 if ch == "." else int(ch)
            if c & 1:
                b0 |= 0x80 >> i
            if c & 2:
                b1 |= 0x80 >> i
        lo.append(b0)
        hi.append(b1)
    return bytes(lo + hi)


def T(*rows):
    return enc(list(rows))


def solid(c):
    return enc([str(c) * 8] * 8)


