def font_rows(ch, ink="3", bg="1"):
    g = FONT[ch]
    rows = []
    for r in g + ["......"]:
        rows.append("".join(ink if c == "#" else bg for c in (r + "......")[:8]))
    return rows


def font_tile(ch):
    return enc(font_rows(ch))


