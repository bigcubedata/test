def enc(rows):
    assert len(rows) == 8, rows
    lo, hi = [], []
    for r in rows:
        r = (r + "........")[:8]
        b0 = b1 = 0
        for i, ch in enumerate(r):
            c = 0 if ch == "." else int(ch)
            if c & 1:
                b0 |= 0x80 >> i
            if c & 2:
                b1 |= 0x80 >> i
        lo.append(b0)
        hi.append(b1)
    return bytes(lo + hi)


def T(*rows):
    return enc(list(rows))


def solid(c):
    return enc([str(c) * 8] * 8)


def grid_tiles(px, w_tiles, h_tiles):
    """px: 行字符串列表('.'/'1'/'2'/'3'),切成瓦片(行优先)。"""
    out = []
    for ty in range(h_tiles):
        for tx in range(w_tiles):
            out.append(enc([px[ty * 8 + y][tx * 8:tx * 8 + 8] for y in range(8)]))
    return out


