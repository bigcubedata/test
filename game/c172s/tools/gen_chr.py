def line_tile(x0, y0, x1, y1, c="2"):
    g = [["." for _ in range(8)] for _ in range(8)]
    steps = max(abs(x1 - x0), abs(y1 - y0), 1)
    for i in range(steps + 1):
        x = round(x0 + (x1 - x0) * i / steps)
        y = round(y0 + (y1 - y0) * i / steps)
        if 0 <= x < 8 and 0 <= y < 8:
            g[y][x] = c
    return enc(["".join(r) for r in g])


