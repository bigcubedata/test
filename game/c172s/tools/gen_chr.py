def papi2(l, r):
    g = [["." for _ in range(8)] for _ in range(8)]
    for cx, c in ((1, l), (5, r)):
        for dy in range(3):
            for dx in range(3):
                g[2 + dy][cx + dx] = c
    return enc(["".join(r) for r in g])


