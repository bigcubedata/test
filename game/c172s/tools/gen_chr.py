def shear(art, direction):
    """direction=+1 抬头(机头上移),-1 低头。按列整体平移。"""
    h = len(art)
    w = len(art[0])
    grid = [["." for _ in range(w)] for _ in range(h)]
    for y, row in enumerate(art):
        for x, c in enumerate(row):
            if c == ".":
                continue
            dy = -direction * ((x - 10) // 8)  # 尾部与机头反向偏移
            ny = y + dy
            if 0 <= ny < h:
                grid[ny][x] = c
    return ["".join(r) for r in grid]


def add_prop(art, phase):
    """在机头前(x=22-23)画竖直桨叶虚影。"""
    grid = [list(r) for r in art]
    # 找机头高度中心:第 9 行附近
    for y in range(3, 14):
        on = (y + phase * 2) % 4 < 2
        if on:
            grid[y][22] = "k"
        else:
            grid[y][23] = "k"
    return ["".join(r) for r in grid]


def plane_tiles(art):
    m = {".": ".", "k": "1", "w": "2", "r": "3"}
    rows = ["".join(m[c] for c in r) for r in art]
    tiles = []
    for ty in range(2):
        for tx in range(3):
            sub = [rows[ty * 8 + y][tx * 8 : tx * 8 + 8] for y in range(8)]
            tiles.append(enc(sub))
    return tiles  # TL TM TR BL BM BR


