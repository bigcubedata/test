def scale2(ch):
    """返回 4 个瓦片 (TL, TR, BL, BR),黑底白字。"""
    src = font_rows(ch)
    big = []
    for r in src:
        rr = "".join(c * 2 for c in r)
        big.append(rr)
        big.append(rr)
    tl = [r[0:8] for r in big[0:8]]
    tr = [r[8:16] for r in big[0:8]]
    bl = [r[0:8] for r in big[8:16]]
    br = [r[8:16] for r in big[8:16]]
    return enc(tl), enc(tr), enc(bl), enc(br)


