def shear(art, direction):
    h, w = len(art), len(art[0])
    grid = [["." for _ in range(w)] for _ in range(h)]
    for y, row in enumerate(art):
        for x, c in enumerate(row):
            if c == ".":
                continue
            ny = y + (-direction * ((x - 10) // 8))
            if 0 <= ny < h:
                grid[ny][x] = c
    return ["".join(r) for r in grid]


def add_prop(art, phase):
    grid = [list(r) for r in art]
    for y in range(3, 14):
        if (y + phase * 2) % 4 < 2:
            grid[y][22] = "k"
        else:
            grid[y][23] = "k"
    return ["".join(r) for r in grid]


def plane_tiles(art):
    m = {".": ".", "k": "1", "w": "2", "r": "3"}
    rows = ["".join(m[c] for c in r) for r in art]
    return grid_tiles(rows, 3, 2)


