def bevel(mask):
    """浮雕汉字:上/左受光缘 c3,下/右暗缘 c1,笔画心 c2。"""
    H, W = len(mask), len(mask[0])
    out = []
    for y in range(H):
        row = []
        for x in range(W):
            if mask[y][x] != "#":
                row.append(".")
                continue
            up = y > 0 and mask[y - 1][x] == "#"
            lf = x > 0 and mask[y][x - 1] == "#"
            dn = y < H - 1 and mask[y + 1][x] == "#"
            rt = x < W - 1 and mask[y][x + 1] == "#"
            if not up or not lf:
                row.append("3")
            elif not dn or not rt:
                row.append("1")
            else:
                row.append("2")
        out.append("".join(row))
    return out


