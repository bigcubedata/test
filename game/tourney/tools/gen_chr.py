# —— 程序化画布(避免手打长串)——

def canvas(w, h):
    return [["." for _ in range(w)] for _ in range(h)]


def R(c, x0, y0, x1, y1, v):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            c[y][x] = v


def P(c, x, y, v):
    c[y][x] = v


def outline(c, y_max=None):
    H = len(c)
    W = len(c[0])
    ym = H if y_max is None else y_max
    src = [row[:] for row in c]
    for y in range(ym):
        for x in range(W):
            if src[y][x] != ".":
                continue
            hit = False
            for dy in (-1, 0, 1):
                for dx in (-1, 0, 1):
                    yy, xx = y + dy, x + dx
                    if 0 <= yy < H and 0 <= xx < W and src[yy][xx] in "23":
                        hit = True
            if hit:
                c[y][x] = "1"
    return c


def rows_of(c):
    return ["".join(r) for r in c]


def horse(frame):
    """右向战马 24×16:c1 轮廓/蹄/尾,c2 棕身,c3 鬃/鞍毯。"""
    c = canvas(24, 16)
    R(c, 3, 6, 18, 10, "2")          # 躯干
    R(c, 15, 3, 18, 6, "2")          # 颈
    R(c, 17, 1, 21, 3, "2")          # 头
    R(c, 21, 3, 23, 4, "2")          # 吻
    P(c, 18, 0, "2")
    P(c, 20, 0, "2")                 # 耳
    R(c, 16, 2, 17, 4, "3")          # 鬃
    R(c, 8, 6, 12, 9, "3")           # 鞍毯
    R(c, 1, 6, 2, 7, "1")            # 尾
    P(c, 0, 8, "1")
    P(c, 1, 8, "1")
    P(c, 1, 9, "1")
    if frame == 0:                   # 伸展相
        R(c, 4, 11, 5, 14, "2")
        R(c, 9, 11, 10, 13, "2")
        R(c, 14, 11, 15, 13, "2")
        R(c, 19, 11, 20, 14, "2")
        R(c, 4, 15, 5, 15, "1")
        R(c, 19, 15, 20, 15, "1")
        R(c, 9, 14, 10, 14, "1")
        R(c, 14, 14, 15, 14, "1")
    else:                            # 收拢相
        R(c, 6, 11, 7, 14, "2")
        R(c, 9, 11, 10, 12, "2")
        R(c, 14, 11, 15, 12, "2")
        R(c, 17, 11, 18, 14, "2")
        R(c, 6, 15, 7, 15, "1")
        R(c, 17, 15, 18, 15, "1")
        P(c, 9, 13, "1")
        P(c, 10, 13, "1")
        P(c, 14, 13, "1")
        P(c, 15, 13, "1")
    outline(c, y_max=11)             # 躯干以上描边,腿保持利落
    P(c, 20, 2, "1")                 # 眼
    return rows_of(c)


def knight_px():
    """骑士 16×16(马背上,右向):c1 轮廓/视缝,c2 罩袍,c3 钢盔/胸甲。"""
    c = canvas(16, 16)
    R(c, 6, 1, 10, 4, "3")           # 盔
    R(c, 5, 5, 10, 10, "2")          # 躯干
    R(c, 7, 6, 8, 7, "3")            # 胸甲片
    R(c, 10, 6, 12, 8, "2")          # 前臂
    R(c, 5, 11, 9, 12, "2")          # 鞍部下摆
    R(c, 6, 13, 7, 14, "2")          # 近侧腿
    outline(c)
    P(c, 9, 3, "1")                  # 视缝(朝前)
    P(c, 10, 3, "1")
    P(c, 6, 15, "1")                 # 靴尖
    P(c, 7, 15, "1")
    return rows_of(c)


